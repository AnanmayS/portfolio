/*
  The handful of stroke icons the site uses, on links, buttons and card
  titles. All inherit currentColor so the same glyph works on ink, on muted
  text, and reversed on a filled button.
*/

type IconProps = { size?: number; className?: string };

function Icon({
  size = 14,
  className,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

